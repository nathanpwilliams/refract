def write_course(package: bytes, out: Path) -> list[str]:
    """Extract the SCORM zip and add demo chrome around it.

    The package's own files are written unchanged — this is the real export,
    not a rebuild of it. index.html gets a navigation bar, a licence footer
    and one extra stylesheet link; nothing else is touched, and the SCORM
    runtime still finds no LMS and so runs in preview mode.
    """
    out.mkdir(parents=True, exist_ok=True)
    written = []
    with zipfile.ZipFile(io.BytesIO(package)) as zf:
        for name in zf.namelist():
            (out / name).write_bytes(zf.read(name))
            written.append(name)

    index = (out / "index.html").read_text(encoding="utf-8")
    index = index.replace(
        '<link rel="stylesheet" href="styles.css">',
        '<link rel="stylesheet" href="styles.css">\n'
        '  <link rel="stylesheet" href="demo.css">')
    index = index.replace("<body>", "<body>\n" + COURSE_BAR, 1)
    index = index.replace("</body>",
                          COURSE_FOOT.format(repo=REPO_URL) + "</body>", 1)
    (out / "index.html").write_text(index, encoding="utf-8")
    (out / "demo.css").write_text(COURSE_CSS, encoding="utf-8")
    written.append("demo.css")
    return written


# --------------------------------------------------------------------- safety

SECRET_PATTERNS = [
    (r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}", "email address"),
    (r"sk-ant-", "Anthropic API key prefix"),
    (r"postgres(?:ql)?://", "connection string"),
    (r"\.supabase\.co", "Supabase project host"),
    (r"eyJ[A-Za-z0-9_-]{10,}", "JWT"),
    (r"ANTHROPIC_API_KEY|DATABASE_URL|SUPABASE_[A-Z_]+", "credential variable"),
    (r"-----BEGIN [A-Z ]*PRIVATE KEY", "private key"),
]


def scan_for_secrets(root: Path, extra_forbidden: list[str]) -> list[str]:
    """Fail the build rather than publish a credential or a personal detail."""
    problems = []
    for path in sorted(root.rglob("*")):
        if not path.is_file():
            continue
        try:
            text = path.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            problems.append(f"{path}: not UTF-8 text; refusing to publish a binary")
            continue
        for pattern, label in SECRET_PATTERNS:
            for m in re.finditer(pattern, text):
                problems.append(f"{path}: possible {label}: {m.group(0)[:48]!r}")
        for value in extra_forbidden:
            if value and value in text:
                problems.append(f"{path}: contains a value that must not ship: {value[:12]}…")
    return problems


def scan_for_external_requests(root: Path) -> list[str]:
    """Every asset reference must be relative; links out are fine."""
    problems = []
    loaders = re.compile(
        r"""(?:src|href)\s*=\s*["'](?P<url>[^"']+)["']|url\(\s*(?P<u2>[^)]+)\)""")
    for path in sorted(root.rglob("*.html")):
        text = path.read_text(encoding="utf-8")
        for m in loaders.finditer(text):
            url = (m.group("url") or m.group("u2") or "").strip("'\" ")
            if not url.startswith(("http://", "https://", "//")):
                continue
            tag_start = text.rfind("<", 0, m.start())
            tag = text[tag_start:m.start()].lower()
            if "<a " in tag:
                continue            # a link the reader may click is not a request
            problems.append(f"{path}: loads an external resource: {url}")
    for path in sorted(root.rglob("*.css")):
        text = path.read_text(encoding="utf-8")
        for m in re.finditer(r"""url\(\s*['"]?(https?:)?//""", text):
            problems.append(f"{path}: CSS loads an external resource")
        if "@import" in text and "http" in text:
            problems.append(f"{path}: CSS @import of a remote stylesheet")
    return problems


# ----------------------------------------------------------------- data access

async def load(job_id: str, version_id: str) -> dict:
    async with db.pool().acquire() as conn:
        job = await conn.fetchrow(
            """select tenant_id, plan, evidence, status, source_version_id,
                      audience_profile_id, target_version_id
               from adaptation_jobs where id = $1""", job_id)
        if job is None:
            raise SystemExit(f"job {job_id} not found")
        if job["evidence"] is None:
            raise SystemExit(f"job {job_id} has no evidence (status {job['status']})")
        if str(job["target_version_id"]) != version_id:
            raise SystemExit(
                f"job {job_id} produced version {job['target_version_id']}, "
                f"not {version_id}")
        tenant_id = str(job["tenant_id"])

        version = await conn.fetchrow(
            """select cv.label, cv.status, c.title as course_title,
                      ap.name as profile_name
               from course_versions cv
               join courses c on c.id = cv.course_id
               left join audience_profiles ap on ap.id = cv.audience_profile_id
               where cv.id = $1""", version_id)
        if version["status"] != "published":
            raise SystemExit(f"version {version_id} is {version['status']}, not published")

        rev_rows = await conn.fetch(
            """select br.block_id, br.original, br.generated, br.review_status,
                      br.disposition_reason, cb.position, cb.block_type,
                      l.title as lesson, m.position as mpos, l.position as lpos
               from block_revisions br
               join content_blocks cb on cb.id = br.block_id
               join lessons l on l.id = cb.lesson_id
               join modules m on m.id = l.module_id
               where br.job_id = $1
               order by m.position, l.position, cb.position""", job_id)

        halted_rows = await conn.fetch(
            """select id, created_at, evidence from adaptation_jobs
               where status = 'halted' and source_version_id = $1
                 and audience_profile_id = $2 and evidence is not null
               order by created_at""",
            job["source_version_id"], job["audience_profile_id"])

    revisions = []
    for r in rev_rows:
        generated = json.loads(r["generated"])
        content = generated.get("content")
        revisions.append({
            "block_id": str(r["block_id"]),
            "position": r["position"],
            "block_type": r["block_type"],
            "lesson": r["lesson"],
            "original": json.loads(r["original"]),
            "adapted": content if isinstance(content, dict) else json.loads(r["original"]),
            "plan_reason": generated.get("plan_reason") or "—",
            "instruction": generated.get("adaptation_instruction") or "",
            "review_status": r["review_status"],
        })

    halted = []
    for row in halted_rows:
        ev = json.loads(row["evidence"])
        halted.append({
            "label": f'{ev["touch_rate"]["touched"]} blocks touched, '
                     f'{ev["checks"]["failed"]} check failure(s), '
                     f'{ev["findings"]["blockers"]} blocking finding(s)',
            "causes": [_shorten(c) for c in ev["halt_causes"]],
        })

    return {
        "tenant_id": tenant_id,
        "meta": {
            "job_id": job_id,
            "version_id": version_id,
            "label": version["label"],
            "course_title": version["course_title"],
            "profile_name": version["profile_name"] or "this audience",
        },
        "evidence": json.loads(job["evidence"]),
        "plan": json.loads(job["plan"]),
        "revisions": revisions,
        "halted": halted,
    }


def _shorten(cause: str, limit: int = 300) -> str:
    cause = " ".join(cause.split())
    return cause if len(cause) <= limit else cause[:limit].rstrip(" ,;") + "…"


