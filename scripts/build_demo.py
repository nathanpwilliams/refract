def nav_links(page: str, depth: int) -> str:
    up = "../" * depth
    items = [("index.html", "Overview", "index"),
             ("course/index.html", "Course demo", "course"),
             ("report.html", "Run report", "report")]
    out = []
    for href, label, key in items:
        current = ' aria-current="page"' if key == page else ""
        out.append(f'<a href="{up}{href}"{current}>{esc(label)}</a>')
    return "\n        ".join(out)


