def render_content(block_type: str, content: dict) -> str:
    """One content block as readable HTML, for the side-by-side panes."""
    c = content or {}
    if block_type == "heading":
        return f"<p><b>{esc(c.get('text'))}</b></p>"
    if block_type in ("text", "callout"):
        body = scorm.md_to_html(c.get("markdown") or "")
        if block_type == "callout" and c.get("variant"):
            label = esc(str(c["variant"]).replace("_", " "))
            return f'<p class="kind">Callout — {label}</p>{body}'
        return body
    if block_type == "image":
        return (f"<p><b>Alt text:</b> {esc(c.get('alt_text'))}</p>"
                f"<p><b>Caption:</b> {esc(c.get('caption'))}</p>")
    if block_type == "knowledge_check":
        opts = "".join(
            f'<li><span class="mark">{"Correct" if o.get("correct") else "Incorrect"}'
            f'</span> — {esc(o.get("text"))}'
            + (f'<br><span class="fb">{esc(o.get("feedback"))}</span>' if o.get("feedback") else "")
            + "</li>"
            for o in (c.get("options") or [])
        )
        return (f"<p>{esc(c.get('question'))}</p>"
                f'<ul class="opts">{opts}</ul>')
    if block_type == "scenario":
        choices = "".join(
            f'<li><span class="mark">{esc(str(ch.get("quality") or "—").title())}'
            f'</span> — {esc(ch.get("text"))}'
            + (f'<br><span class="fb">{esc(ch.get("consequence_md"))}</span>'
               if ch.get("consequence_md") else "")
            + "</li>"
            for ch in (c.get("choices") or [])
        )
        return (f'<div class="situation">{scorm.md_to_html(c.get("situation_md") or "")}</div>'
                f'<ul class="opts">{choices}</ul>')
    if block_type == "code":
        return f"<pre><code>{esc(c.get('source'))}</code></pre>"
    if block_type == "table":
        head = "".join(f"<th>{esc(h)}</th>" for h in (c.get("headers") or []))
        rows = "".join(
            "<tr>" + "".join(f"<td>{esc(cell)}</td>" for cell in row) + "</tr>"
            for row in (c.get("rows") or [])
        )
        return f'<div class="scroll"><table><thead><tr>{head}</tr></thead><tbody>{rows}</tbody></table></div>'
    if block_type == "video_embed":
        return f"<p><b>{esc(c.get('title'))}</b></p>"
    # Unknown shape: show it rather than drop it, escaped.
    return f"<pre><code>{esc(json.dumps(c, indent=2))}</code></pre>"


